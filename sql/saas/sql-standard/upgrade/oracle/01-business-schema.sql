-- ##付款表增加“交易时间”字段
DECLARE cnt NUMBER;
BEGIN
SELECT COUNT(*) INTO cnt
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'NIS_BILLHEAD'
  AND COLUMN_NAME = 'TRANS_TIME';
IF cnt = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE NIS_BILLHEAD ADD TRANS_TIME TIMESTAMP(6)';
ELSE
        EXECUTE IMMEDIATE 'ALTER TABLE NIS_BILLHEAD MODIFY TRANS_TIME TIMESTAMP(6)';
END IF;
END;
/

-- ##企业版本管理表增加“第一次成功部署时间”字段
DECLARE
    v_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_COUNT
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'BP_TENANT_VERSION_MANAGER'
      AND COLUMN_NAME = 'FIRST_DEPLOY_TIME';
    IF v_COUNT < 1 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE BP_TENANT_VERSION_MANAGER ADD FIRST_DEPLOY_TIME DATE';
        EXECUTE IMMEDIATE 'COMMENT ON COLUMN BP_TENANT_VERSION_MANAGER.FIRST_DEPLOY_TIME IS ''第一次成功部署时间''';
    END IF;
END;
