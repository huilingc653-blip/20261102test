--       本批 4 个源脚本均来自内管工程 bt-saas-management，故内容全部落在本目录
--       03-management-schema.sql / 04-management-data.sql；01/02 本批无需新增内容，
--       其内容由其它变更维护，本批未作改动。
--       建表按模板「场景 1：新增表」写成先删后建：DROP TABLE（吞异常）+ 原生 CREATE TABLE。
--       即每次执行都会重建这 10 张表，表内既有数据不保留——后果见下方「先删后建的影响」。
--       COMMENT ON 为替换语义，无条件重放即可正确落注释。
--       主键按模板建表示例写在列上（ID ... NOT NULL PRIMARY KEY），不使用表级 CONSTRAINT。
--       字段含义只在本文件用 COMMENT ON COLUMN 落库（MySQL 侧按模板示例不写列级注释），
--       因此本文件同时充当两方言共用的字段字典。
--
--       【与源脚本 scf_oracle.sql 的差异：列宽对齐 MySQL】
--       源脚本 scf_oracle.sql 是 scf_mysql.sql 的机械转换，若干列宽明显偏窄
--       （如 SCF_PAY_FIELD_CONFIG.FIELD_DEF_VAL 50 vs MySQL varchar(500)、
--        SCF_CUST_FIELD_CONFIG.FIELD_NAME 60 vs varchar(200)、
--        SCF_PAY_CONFIG.FIELD_CODE 50 vs varchar(100)、
--        SCF_PLATFORM.RMK 200 vs varchar(500)、SCF_PRODUCT.PRODUCT_NAME 100 vs varchar(200)）。
--       这些列多为用户可录入内容，窄列会导致「同一笔配置在 MySQL 存得下、在 Oracle 报
--       ORA-12899」。按模板「MySQL 与 Oracle 成对维护，业务对象保持对应」的要求，
--       本脚本将列宽对齐 MySQL 侧定义，并以本文件为唯一口径（表会被重建，不再沿用旧列宽）。
--
--       【先删后建的影响（重要）】
--       本文件采用模板「场景 1：新增表」的先删后建形式，执行时这 10 张表一律 DROP 后重建，
--       表内既有数据不保留。其中：
--         - SCF_VOUCHER_CUSTOM_FIELD 在基线 sql-standard/oracle/06-business-schema.sql 中已存在，
--           存放用户录入的自定义字段值；
--         - SYS_TENANT_SCHEDULED_TASK 及其余 SCF_* 表，在部分环境已按旧源脚本
--           （scf_oracle.sql / dev_20260930_oracle.sql）建过。
--       凡此类环境，执行本脚本会清空这些表的数据。MySQL 侧对应脚本用的是
--       CREATE TABLE IF NOT EXISTS，不做重建——两方言在这一点上行为不同。
--       若要在已有数据的环境上执行，请先把本文件改回 USER_TABLES 存在性保护写法。
--
--       【SCF_VOUCHER_CUSTOM_FIELD 口径】
--       该表基线定义为规范口径（FIELD_CODE VARCHAR2(100)、FIELD_NAME VARCHAR2(200)、
--       FIELD_ID NOT NULL），源脚本 scf_oracle.sql 内的旧副本（50/100/可空）不予采用。
