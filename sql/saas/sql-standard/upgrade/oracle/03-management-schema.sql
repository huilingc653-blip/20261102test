--       二、租户定时任务（来源 dev_20260930_oracle.sql）
--         10. SYS_TENANT_SCHEDULED_TASK 租户定时任务分配表
-- 来源：bt-saas-management/bt-saas-management-web/src/main/webapp/sql/
--         scf_oracle.sql、dev_20260930_oracle.sql
