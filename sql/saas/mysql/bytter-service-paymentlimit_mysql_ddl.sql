-- 付款办理、资金收付增加银行落地限额处理结果
-- LANDING_LIMIT_RESULT：0=待执行（等待银行限额审批）/ A=银行同意支付 / R=银行拒绝支付；NULL=未涉及落地
DROP PROCEDURE IF EXISTS PRO_ADD_LANDING_LIMIT_RESULT;
DELIMITER $$
CREATE PROCEDURE PRO_ADD_LANDING_LIMIT_RESULT()
BEGIN
    IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'NIS_BILLHEAD' AND COLUMN_NAME = 'LANDING_LIMIT_RESULT') THEN
ALTER TABLE `NIS_BILLHEAD` ADD COLUMN `LANDING_LIMIT_RESULT` CHAR(1) NULL DEFAULT NULL COMMENT '落地限额处理结果(0=待执行/A=银行同意支付/R=银行拒绝支付)';
END IF;
    IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'FEX_CASH_FLOW' AND COLUMN_NAME = 'LANDING_LIMIT_RESULT') THEN
ALTER TABLE `FEX_CASH_FLOW` ADD COLUMN `LANDING_LIMIT_RESULT` CHAR(1) NULL DEFAULT NULL COMMENT '落地限额处理结果(0=待执行/A=银行同意支付/R=银行拒绝支付)';
END IF;
END$$
DELIMITER ;
CALL PRO_ADD_LANDING_LIMIT_RESULT();
DROP PROCEDURE IF EXISTS PRO_ADD_LANDING_LIMIT_RESULT;
