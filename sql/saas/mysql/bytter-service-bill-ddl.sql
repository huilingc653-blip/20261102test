##增加字段
DROP PROCEDURE IF EXISTS PRO_ADD_COL;
DELIMITER $$
CREATE PROCEDURE PRO_ADD_COL()
BEGIN
IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE()  AND TABLE_NAME = 'CMS_INL_REPAY' AND COLUMN_NAME = 'REAL_INTEREST') THEN
ALTER TABLE CMS_INL_REPAY ADD COLUMN REAL_INTEREST DECIMAL(15,2);
ELSE
ALTER TABLE CMS_INL_REPAY MODIFY COLUMN REAL_INTEREST DECIMAL(15,2);
END IF;
END$$
DELIMITER ;
CALL PRO_ADD_COL();
DROP PROCEDURE IF EXISTS PRO_ADD_COL;
