-- ============================================= BT_CURRENCY ====================================start
DROP TABLE BT_CURRENCY ;
CREATE TABLE BT_CURRENCY (
ID VARCHAR2(32) NOT NULL PRIMARY KEY,
CUR_CODE VARCHAR2(10) NOT NULL ,
CUR_NAME VARCHAR2(30) NOT NULL ,
ENGLISH_CODE VARCHAR2(30)  ,
CUR_EXRATE NUMBER  ,
CUR_SIGN VARCHAR2(10)  ,
NATURAL_SIGN VARCHAR2(1)  ,
PB_SCALE_CODE VARCHAR2(20)  ,
RMK VARCHAR2(255)  ,
VALID_SIGN VARCHAR2(1)  ,
CREATE_DATE DATE  ,
CREATE_BY VARCHAR2(32)  ,
UPDATE_DATE DATE  ,
UPDATE_BY VARCHAR2(32)  ,
IS_SYSTEM VARCHAR2(1)  ,
NONWORK_DAY_RULE VARCHAR2(1)  ,
NONWORK_DAY VARCHAR2(30)  ,
SYS_CUR_ID VARCHAR2(32)  );
COMMENT ON TABLE BT_CURRENCY IS '币别表'
COMMENT ON COLUMN BT_CURRENCY.NONWORK_DAY_RULE IS '非工作日规则'
COMMENT ON COLUMN BT_CURRENCY.NONWORK_DAY IS '非工作日设置'
COMMENT ON COLUMN BT_CURRENCY.SYS_CUR_ID IS '系统币种ID'
COMMENT ON COLUMN BT_CURRENCY.ID IS 'id'
COMMENT ON COLUMN BT_CURRENCY.CUR_CODE IS '币别编码'
COMMENT ON COLUMN BT_CURRENCY.CUR_NAME IS '币别名称'
COMMENT ON COLUMN BT_CURRENCY.ENGLISH_CODE IS '英文简码'
COMMENT ON COLUMN BT_CURRENCY.CUR_EXRATE IS '汇率'
COMMENT ON COLUMN BT_CURRENCY.CUR_SIGN IS '币别符号'
COMMENT ON COLUMN BT_CURRENCY.NATURAL_SIGN IS '是否本位币'
COMMENT ON COLUMN BT_CURRENCY.PB_SCALE_CODE IS '人行编码'
COMMENT ON COLUMN BT_CURRENCY.RMK IS '备注'
COMMENT ON COLUMN BT_CURRENCY.VALID_SIGN IS '有效标志'
COMMENT ON COLUMN BT_CURRENCY.CREATE_DATE IS '创建日期'
COMMENT ON COLUMN BT_CURRENCY.CREATE_BY IS '创建人登录名称'
COMMENT ON COLUMN BT_CURRENCY.UPDATE_DATE IS '更新日期'
COMMENT ON COLUMN BT_CURRENCY.UPDATE_BY IS '更新人登录名称'
COMMENT ON COLUMN BT_CURRENCY.IS_SYSTEM IS '是否系统初始化'
-- ============================================= BT_CURRENCY ======================================end
