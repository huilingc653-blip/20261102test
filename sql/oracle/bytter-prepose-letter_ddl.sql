DROP TABLE GUA_PERFORM_REG ;
CREATE TABLE GUA_PERFORM_REG (
ID VARCHAR2(32) NOT NULL PRIMARY KEY,
GUARA_ID VARCHAR2(32)  ,
CONTRACT_NO VARCHAR2(32)  ,
CONTRACT_DATE DATE  ,
PAYMENT_METHOD VARCHAR2(50)  ,
PAYMENT_DATE DATE  ,
GUA_NUMBER NUMBER  ,
RMK VARCHAR2(500)  ,
ATTACHMENT_ID VARCHAR2(32)  ,
STATUS NUMBER  ,
CREATE_DATE DATE  ,
CREATE_BY VARCHAR2(50)  ,
UPDATE_DATE DATE  ,
UPDATE_BY VARCHAR2(50)  ,
BANK_NAME VARCHAR2(255)  ,
CORP_NAME VARCHAR2(255)  ,
CUR_NAME VARCHAR2(255)  );
COMMENT ON TABLE GUA_PERFORM_REG IS '履行登记表'
COMMENT ON COLUMN GUA_PERFORM_REG.ID IS '主键'
COMMENT ON COLUMN GUA_PERFORM_REG.GUARA_ID IS '保函申请ID'
COMMENT ON COLUMN GUA_PERFORM_REG.CONTRACT_NO IS '合同编号'
COMMENT ON COLUMN GUA_PERFORM_REG.CONTRACT_DATE IS '合同签订日期'
COMMENT ON COLUMN GUA_PERFORM_REG.PAYMENT_METHOD IS '收款方式'
COMMENT ON COLUMN GUA_PERFORM_REG.PAYMENT_DATE IS '收款日期'
COMMENT ON COLUMN GUA_PERFORM_REG.GUA_NUMBER IS '保函份数'
COMMENT ON COLUMN GUA_PERFORM_REG.RMK IS '备注'
COMMENT ON COLUMN GUA_PERFORM_REG.ATTACHMENT_ID IS '附件ID'
COMMENT ON COLUMN GUA_PERFORM_REG.STATUS IS '状态'
COMMENT ON COLUMN GUA_PERFORM_REG.CREATE_DATE IS '创建日期'
COMMENT ON COLUMN GUA_PERFORM_REG.CREATE_BY IS '创建人登录名称'
COMMENT ON COLUMN GUA_PERFORM_REG.UPDATE_DATE IS '更新日期'
COMMENT ON COLUMN GUA_PERFORM_REG.UPDATE_BY IS '更新人登录名称'
-- ============================================= GUA_PERFORM_REG ======================================end
