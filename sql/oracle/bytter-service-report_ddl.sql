COMMENT ON COLUMN BI_REMAIN_TERM.SORT IS '排序'
COMMENT ON COLUMN BI_REMAIN_TERM.CREATE_BY IS '创建人'
COMMENT ON COLUMN BI_REMAIN_TERM.CREATE_DATE IS '创建日期'
COMMENT ON COLUMN BI_REMAIN_TERM.UPDATE_BY IS '修改人'
COMMENT ON COLUMN BI_REMAIN_TERM.UPDATE_DATE IS '修改日期'
-- ============================================= BI_REMAIN_TERM ======================================end
