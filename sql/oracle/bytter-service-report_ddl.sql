DROP TABLE BI_REMAIN_TERM ;
CREATE TABLE BI_REMAIN_TERM (
ID VARCHAR2(32) NOT NULL PRIMARY KEY,
TERM_NAME VARCHAR2(100)  ,
IS_VALID VARCHAR2(4)  ,
SORT NUMBER  ,
CREATE_BY VARCHAR2(32)  ,
CREATE_DATE DATE  ,
UPDATE_BY VARCHAR2(32)  ,
UPDATE_DATE DATE  );
